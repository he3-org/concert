import { describe, it, expect } from 'vitest';
import {
  extractHeaderVersion,
  compareVersions,
  needsUpdate,
  isManagedFile,
  stampVersion,
} from '../lib/version.js';

describe('extractHeaderVersion', () => {
  it('finds version in markdown header', () => {
    const content = `<!-- AUTO-GENERATED BY CONCERT v0.1.0 — DO NOT EDIT. -->
# Agent file
rest of content`;
    expect(extractHeaderVersion(content)).toBe('0.1.0');
  });

  it('finds version in YAML comment header', () => {
    const content = `# AUTO-GENERATED BY CONCERT v1.2.3 — DO NOT EDIT.
name: concert-status
rest: content`;
    expect(extractHeaderVersion(content)).toBe('1.2.3');
  });

  it('extracts X.Y.Z placeholder version', () => {
    const content = `<!-- AUTO-GENERATED BY CONCERT vX.Y.Z — DO NOT EDIT. -->
# Agent file
rest of content`;
    expect(extractHeaderVersion(content)).toBe('X.Y.Z');
  });

  it('returns null for no header', () => {
    const content = `# Regular comment
no version here`;
    expect(extractHeaderVersion(content)).toBeNull();
  });

  it('only checks first 15 lines', () => {
    const content = `line 1
line 2
line 3
line 4
line 5
line 6
line 7
line 8
line 9
line 10
line 11
line 12
line 13
line 14
line 15
<!-- AUTO-GENERATED BY CONCERT v0.1.0 — DO NOT EDIT. -->
line 17`;
    expect(extractHeaderVersion(content)).toBeNull();
  });

  it('finds version within first 15 lines', () => {
    const content = `line 1
line 2
line 3
line 4
line 5
line 6
line 7
line 8
line 9
line 10
line 11
line 12
line 13
<!-- AUTO-GENERATED BY CONCERT v0.1.0 — DO NOT EDIT. -->
line 15`;
    expect(extractHeaderVersion(content)).toBe('0.1.0');
  });
});

describe('compareVersions', () => {
  it('correctly compares equal versions', () => {
    expect(compareVersions('1.0.0', '1.0.0')).toBe(0);
    expect(compareVersions('0.1.5', '0.1.5')).toBe(0);
  });

  it('correctly compares less-than versions', () => {
    expect(compareVersions('0.1.0', '1.0.0')).toBe(-1);
    expect(compareVersions('1.0.0', '1.1.0')).toBe(-1);
    expect(compareVersions('1.1.0', '1.1.1')).toBe(-1);
  });

  it('correctly compares greater-than versions', () => {
    expect(compareVersions('1.0.0', '0.9.9')).toBe(1);
    expect(compareVersions('2.0.0', '1.9.9')).toBe(1);
    expect(compareVersions('1.2.0', '1.1.9')).toBe(1);
  });

  it('handles different-length versions (missing parts default to 0)', () => {
    expect(compareVersions('1.0', '1.0.0')).toBe(0);
    expect(compareVersions('1', '1.0.0')).toBe(0);
    expect(compareVersions('1.0.1', '1.0')).toBe(1);
  });
});

describe('needsUpdate', () => {
  it('returns true for no header', () => {
    expect(needsUpdate('# Regular file\nno header', '0.1.0')).toBe(true);
  });

  it('returns true for older version', () => {
    const content = '<!-- AUTO-GENERATED BY CONCERT v0.0.9 — DO NOT EDIT. -->\nrest';
    expect(needsUpdate(content, '0.1.0')).toBe(true);
  });

  it('returns false for same version', () => {
    const content = '<!-- AUTO-GENERATED BY CONCERT v0.1.0 — DO NOT EDIT. -->\nrest';
    expect(needsUpdate(content, '0.1.0')).toBe(false);
  });

  it('returns false for newer version (file is ahead)', () => {
    const content = '<!-- AUTO-GENERATED BY CONCERT v0.2.0 — DO NOT EDIT. -->\nrest';
    expect(needsUpdate(content, '0.1.0')).toBe(false);
  });

  it('returns true for X.Y.Z placeholder version', () => {
    const content = '<!-- AUTO-GENERATED BY CONCERT vX.Y.Z — DO NOT EDIT. -->\nrest';
    expect(needsUpdate(content, '1.0.0')).toBe(true);
  });
});

describe('isManagedFile', () => {
  it('detects managed files with markdown header', () => {
    const content = '<!-- AUTO-GENERATED BY CONCERT v0.1.0 — DO NOT EDIT. -->\nrest';
    expect(isManagedFile(content)).toBe(true);
  });

  it('detects managed files with YAML header', () => {
    const content = '# AUTO-GENERATED BY CONCERT v0.1.0 — DO NOT EDIT.\nname: agent';
    expect(isManagedFile(content)).toBe(true);
  });

  it('returns false for non-managed files', () => {
    const content = '# Regular markdown file\nno managed header';
    expect(isManagedFile(content)).toBe(false);
  });
});

describe('stampVersion', () => {
  it('stamps version in markdown header', () => {
    const content = '<!-- AUTO-GENERATED BY CONCERT v0.1.0 — DO NOT EDIT. -->\n# Agent file';
    const result = stampVersion(content, '2.0.0');
    expect(result).toBe('<!-- AUTO-GENERATED BY CONCERT v2.0.0 — DO NOT EDIT. -->\n# Agent file');
  });

  it('stamps version in YAML comment header', () => {
    const content = '# AUTO-GENERATED BY CONCERT v1.2.3 — DO NOT EDIT.\nname: agent';
    const result = stampVersion(content, '3.0.0');
    expect(result).toBe('# AUTO-GENERATED BY CONCERT v3.0.0 — DO NOT EDIT.\nname: agent');
  });

  it('returns content unchanged when no header present', () => {
    const content = '# Regular file\nno header here';
    expect(stampVersion(content, '2.0.0')).toBe(content);
  });

  it('only replaces the first occurrence in first 15 lines', () => {
    const content =
      '<!-- AUTO-GENERATED BY CONCERT v0.1.0 — DO NOT EDIT. -->\nAUTO-GENERATED BY CONCERT v0.1.0 in body';
    const result = stampVersion(content, '2.0.0');
    expect(result).toBe(
      '<!-- AUTO-GENERATED BY CONCERT v2.0.0 — DO NOT EDIT. -->\nAUTO-GENERATED BY CONCERT v0.1.0 in body'
    );
  });

  it('stamps version in header with frontmatter above', () => {
    const content =
      '---\nname: concert-init\n---\n\n<!-- AUTO-GENERATED BY CONCERT v1.9.0 — DO NOT EDIT. -->\n# Agent';
    const result = stampVersion(content, '1.10.0');
    expect(result).toBe(
      '---\nname: concert-init\n---\n\n<!-- AUTO-GENERATED BY CONCERT v1.10.0 — DO NOT EDIT. -->\n# Agent'
    );
  });

  it('stamps version replacing X.Y.Z placeholder', () => {
    const content = '<!-- AUTO-GENERATED BY CONCERT vX.Y.Z — DO NOT EDIT. -->\n# Agent file';
    const result = stampVersion(content, '2.0.0');
    expect(result).toBe('<!-- AUTO-GENERATED BY CONCERT v2.0.0 — DO NOT EDIT. -->\n# Agent file');
  });

  it('stamps version replacing X.Y.Z placeholder with frontmatter', () => {
    const content =
      '---\nname: concert-test\n---\n\n<!-- AUTO-GENERATED BY CONCERT vX.Y.Z — DO NOT EDIT. -->\n# Agent';
    const result = stampVersion(content, '1.15.0');
    expect(result).toBe(
      '---\nname: concert-test\n---\n\n<!-- AUTO-GENERATED BY CONCERT v1.15.0 — DO NOT EDIT. -->\n# Agent'
    );
  });
});
